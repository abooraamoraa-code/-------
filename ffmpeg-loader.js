/*
============================================================
NOVA CUT
FFMPEG LOADER
============================================================

هذا الملف مسؤول عن:
1. تحميل محرك FFmpeg
2. تشغيله مرة واحدة
3. إعادة استخدامه
4. إرسال نسبة التحميل إلى processor.js

ملاحظة:
لن نضع كود الواجهة هنا.
ولن نضع كود القص هنا.
هذا الملف هو "بوابة" محرك الفيديو فقط.
============================================================
*/


/*
============================================================
استيراد FFmpeg
============================================================
*/

import {
  FFmpeg
} from "https://esm.sh/@ffmpeg/ffmpeg@0.12.10";


/*
============================================================
استيراد أدوات FFmpeg
============================================================
*/

import {
  toBlobURL
} from "https://esm.sh/@ffmpeg/util@0.12.1";


/*
============================================================
متغير المحرك
============================================================
*/

let ffmpeg = null;


/*
============================================================
حالة المحرك
============================================================
*/

let loadingPromise = null;


/*
============================================================
هل المحرك جاهز؟
============================================================
*/

let isLoaded = false;


/*
============================================================
روابط محرك FFmpeg
============================================================

نستخدم ملفات المحرك من jsDelivr.

هذه الملفات تحتوي على:
- ffmpeg-core.js
- ffmpeg-core.wasm
- ffmpeg-core.worker.js

ونحولها إلى Blob URLs حتى يستطيع
FFmpeg تشغيلها بأمان من المتصفح.
============================================================
*/

const CORE_BASE_URL =
  "https://cdn.jsdelivr.net/npm/@ffmpeg/core@0.12.6/dist/umd";


/*
============================================================
تحميل FFmpeg
============================================================
*/

export async function getFFmpeg(
  onProgress = function () {}
) {

  /*
  ----------------------------------------------------------
  إذا كان المحرك جاهزًا بالفعل
  نعيد نفس النسخة.
  ----------------------------------------------------------
  */

  if (
    ffmpeg &&
    isLoaded
  ) {

    onProgress(
      100
    );

    return ffmpeg;

  }


  /*
  ----------------------------------------------------------
  إذا كان هناك تحميل جارٍ بالفعل
  ننتظر نفس عملية التحميل بدل إنشاء محرك آخر.
  ----------------------------------------------------------
  */

  if (loadingPromise) {

    return await loadingPromise;

  }


  /*
  ----------------------------------------------------------
  بدء عملية التحميل
  ----------------------------------------------------------
  */

  loadingPromise =
    loadEngine(
      onProgress
    );


  try {

    ffmpeg =
      await loadingPromise;

    isLoaded =
      true;

    return ffmpeg;

  } catch (error) {

    /*
    في حالة الفشل نسمح بالمحاولة مرة أخرى.
    */

    ffmpeg = null;

    isLoaded = false;

    throw error;

  } finally {

    loadingPromise = null;

  }

}


/*
============================================================
الدالة الداخلية لتحميل المحرك
============================================================
*/

async function loadEngine(
  onProgress
) {

  /*
  ----------------------------------------------------------
  إنشاء نسخة جديدة
  ----------------------------------------------------------
  */

  const engine =
    new FFmpeg();


  /*
  ----------------------------------------------------------
  مراقبة تقدم التحميل
  ----------------------------------------------------------
  */

  const progressHandler =
    function(event) {

      if (!event) {
        return;
      }


      let progress =
        0;


      /*
      FFmpeg عادة يرسل progress
      بين 0 و 1.
      */

      if (
        typeof event.progress === "number"
      ) {

        progress =
          event.progress * 100;

      }


      /*
      حماية النسبة
      */

      progress =
        Math.max(
          0,
          Math.min(
            100,
            progress
          )
        );


      onProgress(
        progress
      );

    };


  /*
  ----------------------------------------------------------
  تسجيل حدث progress
  ----------------------------------------------------------
  */

  engine.on(
    "progress",
    progressHandler
  );


  /*
  ----------------------------------------------------------
  إنشاء روابط ملفات المحرك
  ----------------------------------------------------------
  */

  onProgress(
    5
  );


  let coreURL = null;

  let wasmURL = null;

  let workerURL = null;


  try {

    /*
    --------------------------------------------------------
    رابط JavaScript الخاص بالمحرك
    --------------------------------------------------------
    */

    coreURL =
      await toBlobURL(
        `${CORE_BASE_URL}/ffmpeg-core.js`,
        "text/javascript"
      );


    onProgress(
      15
    );


    /*
    --------------------------------------------------------
    رابط WASM
    --------------------------------------------------------
    */

    wasmURL =
      await toBlobURL(
        `${CORE_BASE_URL}/ffmpeg-core.wasm`,
        "application/wasm"
      );


    onProgress(
      30
    );


    /*
    --------------------------------------------------------
    رابط Worker
    --------------------------------------------------------

    هذا مهم جدًا لأن FFmpeg يستخدم Worker
    لمعالجة الفيديو بعيدًا عن واجهة الصفحة.
    --------------------------------------------------------
    */

    workerURL =
      await toBlobURL(
        `${CORE_BASE_URL}/ffmpeg-core.worker.js`,
        "text/javascript"
      );


    onProgress(
      40
    );


    /*
    --------------------------------------------------------
    تشغيل المحرك
    --------------------------------------------------------
    */

    await engine.load({

      coreURL,

      wasmURL,

      workerURL

    });


    /*
    --------------------------------------------------------
    نجاح التحميل
    --------------------------------------------------------
    */

    onProgress(
      100
    );


    return engine;


  } catch (error) {

    /*
    --------------------------------------------------------
    تنظيف الروابط إذا حدث خطأ
    --------------------------------------------------------
    */

    try {

      if (coreURL) {

        URL.revokeObjectURL(
          coreURL
        );

      }

    } catch (cleanupError) {}


    try {

      if (wasmURL) {

        URL.revokeObjectURL(
          wasmURL
        );

      }

    } catch (cleanupError) {}


    try {

      if (workerURL) {

        URL.revokeObjectURL(
          workerURL
        );

      }

    } catch (cleanupError) {}


    /*
    --------------------------------------------------------
    إرسال خطأ واضح
    --------------------------------------------------------
    */

    console.error(
      "NOVA CUT FFmpeg LOAD ERROR:",
      error
    );


    throw new Error(
      "تعذر تحميل محرك معالجة الفيديو. " +
      "تأكد من اتصال الإنترنت ثم حاول مرة أخرى."
    );

  } finally {

    /*
    --------------------------------------------------------
    إزالة مستمع التقدم
    --------------------------------------------------------
    */

    try {

      engine.off(
        "progress",
        progressHandler
      );

    } catch (error) {}

  }

}


/*
============================================================
إعادة تشغيل المحرك
============================================================

هذه الدالة سنحتاجها إذا حدث خطأ
وأردنا إعادة إنشاء محرك FFmpeg.
============================================================
*/

export async function resetFFmpeg() {

  /*
  ----------------------------------------------------------
  إيقاف المحرك القديم
  ----------------------------------------------------------
  */

  if (ffmpeg) {

    try {

      if (
        typeof ffmpeg.terminate ===
        "function"
      ) {

        ffmpeg.terminate();

      }

    } catch (error) {

      console.warn(
        "تعذر إنهاء محرك FFmpeg القديم.",
        error
      );

    }

  }


  /*
  ----------------------------------------------------------
  إعادة الحالة
  ----------------------------------------------------------
  */

  ffmpeg = null;

  isLoaded = false;

  loadingPromise = null;

}


/*
============================================================
التحقق من حالة المحرك
============================================================
*/

export function isFFmpegReady() {

  return (
    ffmpeg !== null &&
    isLoaded === true
  );

}


/*
============================================================
الحصول على نسخة المحرك الحالية
============================================================
*/

export function getCurrentFFmpeg() {

  return ffmpeg;

}


